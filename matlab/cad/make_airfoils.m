function files = make_airfoils(outDir)
%MAKE_AIRFOILS Write NACA 4-digit airfoil coordinate files for the wing CAD.
%   files = make_airfoils()         writes into <repo>/cad/airfoils/
%   files = make_airfoils(dir)      writes into dir
%   make_airfoils('--selftest')     checks the generator against hand values
%
%   Why NACA 4-digit: the sections are generated from the published closed
%   form, so every coordinate is reproducible and hand-checkable. Real FS
%   teams use high-lift sections (S1223, E423, CH10) whose coordinates are
%   tabulated; swap them in later by dropping a .dat file of the same format
%   into cad/airfoils/ and the import macro will take it unchanged.
%
%   Two files per section:
%     <name>.dat     normalized x/c, y/c, two columns, Selig order
%                    (trailing edge -> upper surface -> leading edge -> lower
%                    surface -> trailing edge). Read by cad/macros/ImportAirfoil.bas
%     <name>.sldcrv  x y z in mm at the nominal chord, for manual import with
%                    Insert > Curve > Curve Through XYZ Points
%
%   Sections and nominal chords are taken from params/car_params.txt.

if nargin == 1 && strcmp(outDir, '--selftest')
    files = selftest();
    return
end
if nargin < 1 || isempty(outDir)
    outDir = fullfile(repo_root(), 'cad', 'airfoils');
end
if ~isfolder(outDir), mkdir(outDir); end
p = read_car_params();

% name, NACA code, chord (mm), comment
list = {
    'fw_main',   '6412', p.fw_main_chord,  'front wing main element, 6% camber at 40% chord, 12% thick'
    'fw_flap1',  '8410', p.fw_flap1_chord, 'front wing first flap, 8% camber, 10% thick'
    'fw_flap2',  '9409', p.fw_flap2_chord, 'front wing second flap, 9% camber, 9% thick'
    'rw_main',   '6414', p.rw_main_chord,  'rear wing main element, 6% camber, 14% thick (holds the spar)'
    'rw_flap1',  '8410', p.rw_flap1_chord, 'rear wing first flap'
    'rw_flap2',  '9409', p.rw_flap2_chord, 'rear wing second flap'
    'symmetric', '0012', 300,              'reference section for the CFD smoke test and endplate leading edge'
    };

nPts = 80;  % points per surface, cosine spaced so the nose is well resolved
files = strings(0, 1);
for k = 1:size(list, 1)
    [xu, yu, xl, yl] = naca4(list{k, 2}, nPts);
    % Selig order: TE -> upper -> LE -> lower -> TE
    x = [flipud(xu); xl(2:end)];
    y = [flipud(yu); yl(2:end)];
    name = list{k, 1};
    chord = list{k, 3};

    f1 = fullfile(outDir, [name '.dat']);
    fid = fopen(f1, 'w');
    fprintf(fid, '%s NACA %s  (%s) chord %g mm nominal\n', name, list{k, 2}, list{k, 4}, chord);
    fprintf(fid, '%10.6f %10.6f\n', [x y].');
    fclose(fid);

    f2 = fullfile(outDir, [name '.sldcrv']);
    fid = fopen(f2, 'w');
    fprintf(fid, '%.4f\t%.4f\t%.4f\n', [x * chord, y * chord, zeros(size(x))].');
    fclose(fid);
    files(end+1, 1) = string(f1); %#ok<AGROW>
    files(end+1, 1) = string(f2); %#ok<AGROW>
end

% Index file for humans
fid = fopen(fullfile(outDir, 'README.md'), 'w');
fprintf(fid, '# Airfoil coordinate files\n\n');
fprintf(fid, 'Generated by `matlab/cad/make_airfoils.m` from the NACA 4-digit closed form. ');
fprintf(fid, 'Chords come from `params/car_params.txt`.\n\n');
fprintf(fid, '| File | Section | Nominal chord (mm) | Use |\n|---|---|---|---|\n');
for k = 1:size(list, 1)
    fprintf(fid, '| %s.dat / .sldcrv | NACA %s | %g | %s |\n', list{k, 1}, list{k, 2}, list{k, 3}, list{k, 4});
end
fprintf(fid, '\n`.dat` is normalized (x/c, y/c, Selig order) and is what `cad/macros/ImportAirfoil.bas` reads. ');
fprintf(fid, '`.sldcrv` is the same curve in mm at the nominal chord for manual import with ');
fprintf(fid, 'Insert > Curve > Curve Through XYZ Points.\n\n');
fprintf(fid, 'To use a tabulated high-lift section instead (for example S1223), save its coordinates ');
fprintf(fid, 'in the same two-column Selig format as `cad/airfoils/<name>.dat`; the macro does not care which section it is.\n');
fclose(fid);
fprintf('make_airfoils: wrote %d files to %s\n', numel(files), outDir);
end

% ------------------------------------------------------------------------
function [xu, yu, xl, yl] = naca4(code, n)
% NACA 4-digit: camber m (first digit, %), position p (second digit, tenths),
% thickness t (last two digits, %). Closed trailing edge (-0.1036 term).
m = str2double(code(1)) / 100;
p = str2double(code(2)) / 10;
t = str2double(code(3:4)) / 100;
beta = linspace(0, pi, n).';
x = (1 - cos(beta)) / 2;                       % cosine spacing, 0..1
yt = 5 * t * (0.2969 * sqrt(x) - 0.1260 * x - 0.3516 * x.^2 + 0.2843 * x.^3 - 0.1036 * x.^4);
yc = zeros(size(x)); dyc = zeros(size(x));
if m > 0
    i1 = x < p; i2 = ~i1;
    yc(i1) = m / p^2 * (2 * p * x(i1) - x(i1).^2);
    yc(i2) = m / (1 - p)^2 * ((1 - 2 * p) + 2 * p * x(i2) - x(i2).^2);
    dyc(i1) = 2 * m / p^2 * (p - x(i1));
    dyc(i2) = 2 * m / (1 - p)^2 * (p - x(i2));
end
th = atan(dyc);
xu = x - yt .* sin(th); yu = yc + yt .* cos(th);
xl = x + yt .* sin(th); yl = yc - yt .* cos(th);
end

function ok = selftest()
% Hand checks on NACA 0012 (symmetric, so yc = 0 and the thickness
% formula is the whole story):
%   at x/c = 0.30 the half thickness is
%   5*0.12*(0.2969*sqrt(0.3) - 0.1260*0.3 - 0.3516*0.09 + 0.2843*0.027 - 0.1036*0.0081)
%   = 0.6*(0.16262 - 0.03780 - 0.03164 + 0.00768 - 0.00084) = 0.6*0.10001 = 0.06001
%   and the maximum half thickness is ~0.0600 (12% total), near x/c = 0.30.
% On NACA 6412 the camber line peaks at x/c = 0.4 with yc = 0.06.
[xu, yu, xl, yl] = naca4('0012', 400);
[~, i] = min(abs(xu - 0.30));
ok = abs(yu(i) - 0.06001) < 2e-4 && abs(max(yu) - 0.0600) < 2e-4 && all(abs(yl + yu) < 1e-12);
[xu, yu, xl, yl] = naca4('6412', 400);
yc = (yu + yl) / 2;                           % camber line (approx, since xu ~= xl)
[ymax, i] = max(yc);
ok = ok && abs(ymax - 0.06) < 1e-3 && abs((xu(i) + xl(i)) / 2 - 0.4) < 0.01;
% Writing to a temp folder must produce 14 files + README
tmp = tempname; mkdir(tmp);
f = make_airfoils(tmp);
ok = ok && numel(f) == 14 && isfile(fullfile(tmp, 'README.md'));
rmdir(tmp, 's');
if ok
    fprintf('make_airfoils self-test: PASS (NACA 0012 half thickness at x/c=0.3 is 0.0600; NACA 6412 camber peaks at 0.06 near x/c=0.4)\n');
else
    error('make_airfoils self-test: FAIL');
end
end
